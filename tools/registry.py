"""RSOS registry tool (standard library only).

  python3 tools/registry.py check      validate registry/operators.json, the publication rule, code agreement, tests
  python3 tools/registry.py docs       regenerate spec/core/OPERATORS.md from the registry
  python3 tools/registry.py docs --check   fail if spec/core/OPERATORS.md is out of date (CI)
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REG = os.path.join(ROOT, "registry", "operators.json")
DOC = os.path.join(ROOT, "spec", "core", "OPERATORS.md")
STATUS = ["proposed", "specified", "implemented", "tested", "executed"]
REQUIRED = ["id", "tech_name", "symbolic_name", "kind", "signature", "semantics", "errors", "deterministic", "target",
            "status", "evidence", "tests", "safety_class", "origin", "since"]


def load():
    with open(REG, encoding="utf-8") as f:
        return json.load(f)


def in_core(e):
    """The publication rule."""
    return STATUS.index(e["status"]) >= STATUS.index("tested") and bool(e["evidence"])


def check(reg):
    errs = []
    ids, names = set(), set()
    for e in reg["entries"]:
        for k in REQUIRED:
            if k not in e:
                errs.append(f"{e.get('id')}: missing {k}")
        if e.get("status") not in STATUS:
            errs.append(f"{e.get('id')}: bad status {e.get('status')!r}")
        if e["id"] in ids or e["tech_name"] in names:
            errs.append(f"{e['id']}: duplicate id or tech_name")
        ids.add(e["id"]); names.add(e["tech_name"])
        if e.get("safety_class") == "person_facing" and in_core(e) and "consent" not in json.dumps(e):
            errs.append(f"{e['id']}: person-facing entry in Core without a consent statement")
        for t in e.get("tests", []):
            path, _, fn = t.partition("::")
            p = os.path.join(ROOT, path)
            if not os.path.exists(p) or (fn and not re.search(rf"def {re.escape(fn)}\b", open(p).read())):
                errs.append(f"{e['id']}: test not found: {t}")
        for ev in e.get("evidence", []):
            if not os.path.exists(os.path.join(ROOT, ev["report"])):
                errs.append(f"{e['id']}: evidence report not found: {ev['report']}")
    sys.path.insert(0, os.path.join(ROOT, "src"))
    from rsoslang.core.ir import CORE_OPS
    # proposed/specified operations are not built yet; implemented or higher must exist in code, and code nothing else
    reg_ops = {e["tech_name"]: e["symbolic_name"] for e in reg["entries"] if e["kind"] == "operation"
               and e["status"] not in ("proposed", "specified")}
    if set(reg_ops) != set(CORE_OPS):
        errs.append(f"registry operations {sorted(reg_ops)} != code {sorted(CORE_OPS)}")
    for n, sym in reg_ops.items():
        if n in CORE_OPS and CORE_OPS[n][0] != sym:
            errs.append(f"{n}: registry symbolic name {sym} != code {CORE_OPS[n][0]}")
    return errs


def render(reg):
    core = [e for e in reg["entries"] if in_core(e)]
    rest = [e for e in reg["entries"] if not in_core(e)]
    out = ["<!-- Generated by tools/registry.py from registry/operators.json. Do not edit by hand. -->",
           f"# RSOS Core {reg['core_version']}: operator reference", "",
           "Each entry: the Core (technical) name, its RSOS (symbolic) name, what it does, its errors and the evidence "
           "behind it. " + reg["publication_rule"], "",
           "| Core name | RSOS name | Kind | Signature | Familiar equivalent | Status | Evidence |",
           "|---|---|---|---|---|---|---|"]
    for e in core:
        ev = ", ".join(f"[{x['id']}](../../{x['report']})" for x in e["evidence"])
        out.append(f"| `{e['tech_name']}` | `{e['symbolic_name']}` | {e['kind']} | `{e['signature']}` | "
                   f"{e.get('familiar_equivalent', '')} | {e['status']} | {ev} |")
    out += [""]
    for e in core + rest:
        out += [f"## `{e['tech_name']}` ({e['id']})", "",
                f"- **RSOS name:** `{e['symbolic_name']}`" + (f" (also: {', '.join(e['aliases'])})" if e.get("aliases") else ""),
                f"- **Signature:** `{e['signature']}`", f"- **Semantics:** {e['semantics']}"]
        if e.get("preconditions"):
            out.append(f"- **Preconditions:** {'; '.join(e['preconditions'])}")
        if e.get("postconditions"):
            out.append(f"- **Postconditions:** {'; '.join(e['postconditions'])}")
        out += [f"- **Errors:** {', '.join('`'+x+'`' for x in e['errors']) or 'none'}",
                f"- **Deterministic:** {'yes' if e['deterministic'] else 'no'} · **Safety class:** {e['safety_class']}",
                f"- **Status:** {e['status']}" + ("" if in_core(e) else " (not in the Core layer yet: no experiment evidence)"),
                f"- **Tests:** {', '.join('`'+t+'`' for t in e['tests'])}"]
        if e["evidence"]:
            out.append(f"- **Evidence:** {', '.join(x['id'] for x in e['evidence'])}. {e.get('evidence_note', '')}".rstrip())
        if e.get("measured_uses_a7_a8"):
            out.append(f"- **Used by blind planners in A7/A8:** {e['measured_uses_a7_a8']:,} times")
        out += [f"- **Origin:** {', '.join(e['origin'].get('register', [])) or '—'} ({e['origin'].get('language', '')})", ""]
    return "\n".join(out).rstrip() + "\n"


def main(argv):
    reg = load()
    if argv[:1] == ["check"]:
        errs = check(reg)
        for e in errs:
            print("ERROR", e)
        core = [e["tech_name"] for e in reg["entries"] if in_core(e)]
        print(f"{len(reg['entries'])} entries, {len(core)} in Core: {', '.join(core)}")
        return 1 if errs else 0
    if argv[:1] == ["docs"]:
        text = render(reg)
        if "--check" in argv:
            ok = os.path.exists(DOC) and open(DOC, encoding="utf-8").read() == text
            print("OPERATORS.md up to date" if ok else "OPERATORS.md is out of date: run python3 tools/registry.py docs")
            return 0 if ok else 1
        with open(DOC, "w", encoding="utf-8") as f:
            f.write(text)
        print("wrote", os.path.relpath(DOC, ROOT))
        return 0
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
